import {readFile, writeFile, mkdir, readdir, cp} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const types = {'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.js':'text/javascript; charset=utf-8','.json':'application/json; charset=utf-8','.mp3':'audio/mpeg'};
const names = ['index.html','styles.css','app.js','renderer.js','geo.js','labs.js','curriculum.json'];
names.push(...(await readdir(path.join(root,'audio'))).filter(n=>n.endsWith('.mp3')).map(n=>'audio/'+n));
const assets = {};
for(const name of names) {
  const bytes = await readFile(path.join(root,name));
  const binary = name.endsWith('.mp3');
  assets['/'+name] = {body:bytes.toString(binary?'base64':'utf8'),base64:binary,type:types[path.extname(name)]};
}
const course = JSON.parse(assets['/curriculum.json'].body);
const budget = (await readFile(path.join(root,'worker/budget.mjs'),'utf8')).replace(/^export /gm,'');
const api = (await readFile(path.join(root,'worker/api.mjs'),'utf8')).replace(/^import .*budget.mjs';\n/m,'').replace(/^export /gm,'');
if(/^import /m.test(api)) throw new Error('Worker API must be dependency-free');
const output = `// Generated by scripts/build-sites.mjs; edit source files instead.\nconst COURSE=${JSON.stringify(course)};\nconst ASSETS=${JSON.stringify(assets)};\n${budget}\n${api}\nexport default createHandler({course:COURSE,assets:ASSETS});\n`;
await mkdir(path.join(root,'dist/server'),{recursive:true});
await mkdir(path.join(root,'dist/.openai'),{recursive:true});
await writeFile(path.join(root,'dist/server/index.js'),output);
await writeFile(path.join(root,'dist/.openai/hosting.json'),await readFile(path.join(root,'.openai/hosting.json')));
await cp(path.join(root,'drizzle'), path.join(root,'dist/drizzle'), {recursive:true});
console.log(JSON.stringify({workerBytes:Buffer.byteLength(output),assets:names.length,nodes:course.nodes.length}));
