async page => {
  const report={checks:[],errors:[],performance:null};
  const errorListener=e=>report.errors.push(e.message);page.on('pageerror',errorListener);
  const check=(ok,name)=>{if(!ok)throw new Error(name);report.checks.push(name);};
  const state=()=>page.evaluate(()=>geographyApp.getState());
  const settle=()=>page.waitForFunction(()=>!geographyApp.getState().scene.animating,{},{timeout:5000});
  const frame=()=>page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  const hash=()=>page.locator('#scene').evaluate(c=>{const a=c.getContext('2d').getImageData(0,0,c.width,c.height).data;let h=2166136261;for(let i=0;i<a.length;i+=53)h=Math.imul(h^a[i],16777619);return h>>>0;});
  await page.setViewportSize({width:1500,height:1050});await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto('http://127.0.0.1:8768/');await page.waitForFunction(()=>window.geographyApp);
  await page.locator('[data-explore=terrain-steps]').click();await settle();
  check((await state()).followLesson && (await state()).scene.options.parameter===75,'enter topic enables follow and its teaching cue');
  await page.locator('#step-next').click();await settle();
  check((await state()).scene.view==='profile' && (await state()).scene.stage===1,'next narration step changes view and teaching stage');
  await page.screenshot({path:'evidence/upgrade-steps-desktop.png'});
  let box=await page.locator('#scene').boundingBox();
  await page.mouse.move(box.x+box.width*.52,box.y+box.height*.5);await page.mouse.down();await page.mouse.move(box.x+box.width*.6,box.y+box.height*.57,{steps:10});await page.mouse.up();await settle();
  const free=(await state()).scene.camera;
  check(!(await state()).followLesson,'drag gives student camera control');
  await page.locator('#step-next').click();await settle();
  check(JSON.stringify(free)===JSON.stringify((await state()).scene.camera),'next narration cannot steal free camera');
  await page.locator('#follow-lesson').click();await settle();
  check((await state()).followLesson && (await state()).scene.stage===2,'resume follow applies current step');
  await page.locator('[data-view=top]').click();await settle();
  check(Math.abs((await state()).scene.camera.pitch-Math.PI/2)<.002,'top preset is truly top down');
  box=await page.locator('#scene').boundingBox();
  let before=(await state()).scene.camera;
  await page.mouse.move(box.x+box.width*.6,box.y+box.height*.4);await page.mouse.wheel(0,-120);await settle();
  let after=(await state()).scene.camera;
  check(after.zoom>before.zoom && (after.panX!==before.panX || after.panY!==before.panY),'wheel zoom anchors off-center pointer');
  before=after;
  await page.mouse.move(box.x+box.width*.5,box.y+box.height*.45);await page.mouse.down({button:'right'});await page.mouse.move(box.x+box.width*.55,box.y+box.height*.5,{steps:8});await page.mouse.up({button:'right'});await settle();
  after=(await state()).scene.camera;
  check(Math.abs(after.panX-before.panX)>10 && Math.abs(after.yaw-before.yaw)<.001,'right drag pans without rotation');
  await page.locator('#reset-view').click();await settle();
  await page.locator('#scene').focus();await page.keyboard.press('2');await settle();
  check((await state()).scene.view==='top','keyboard preset works');
  await page.keyboard.press('Shift+ArrowRight');await settle();
  check((await state()).scene.camera.panX>0,'keyboard pan works');
  await page.locator('[data-explore=monsoon]').click();
  await page.locator('#motion-toggle').click();await settle();
  check((await state()).scene.paused,'pause freezes moving phenomena');
  const pausedHash=await hash();await page.waitForTimeout(160);
  check(await hash()===pausedHash,'paused pixels remain stationary');
  await page.locator('[data-season="0"]').click();await frame();const winter=await hash();
  await page.locator('[data-season="100"]').click();await frame();const summer=await hash();
  check(winter!==summer && (await page.locator('#experiment-observation').innerText()).includes('水汽'),'winter and summer change picture and explanation even paused');
  await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'evidence/upgrade-monsoon-desktop.png'});
  await page.locator('#motion-toggle').click();
  report.performance=await page.evaluate(()=>new Promise(resolve=>{const spans=[];let previous=performance.now();function next(t){spans.push(t-previous);previous=t;if(spans.length<80)requestAnimationFrame(next);else{const sorted=spans.slice(5).sort((a,b)=>a-b);resolve({userAgent:navigator.userAgent,viewport:[innerWidth,innerHeight],samples:sorted.length,medianFrameMs:sorted[Math.floor(sorted.length*.5)],p95FrameMs:sorted[Math.floor(sorted.length*.95)],note:'Chromium desktop preview; frame intervals, not a GPU benchmark.'});}}requestAnimationFrame(next);}));
  await page.locator('[data-explore=river-system]').click();await page.locator('[data-rain=left]').click();await page.locator('[data-rain=right]').click();await frame();
  const exp=(await state()).scene.experiment;
  check(exp.rain.length===2 && exp.routes.every(r=>r.downhill),'two rainfall routes keep downhill flow to different basins');
  check(exp.routes[0].basin!==exp.routes[1].basin,'watershed routes end in distinct basins');
  await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'evidence/upgrade-watershed-desktop.png'});
  await page.locator('#reset-experiment').click();
  check((await state()).followLesson && !(await state()).scene.experiment.rain.length,'experiment reset clears rain and restores teaching');
  await page.locator('#fullscreen-scene').click();
  check(await page.evaluate(()=>!!document.fullscreenElement||document.body.classList.contains('focus-stage')),'fullscreen enters');
  await page.locator('#fullscreen-scene').click();
  check(await page.evaluate(()=>!document.fullscreenElement&&!document.body.classList.contains('focus-stage')),'fullscreen exits');
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>scrollTo(0,0));
  await page.locator('[data-explore=river-system]').click();await page.locator('[data-view=oblique]').click();
  await page.locator('#motion-toggle').click();await settle();
  await page.locator('#scene').scrollIntoViewIfNeeded();box=await page.locator('#scene').boundingBox();
  const cdp=await page.context().newCDPSession(page);await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
  const cx=box.x+box.width*.46,cy=box.y+box.height*.43;
  before=(await state()).scene.camera;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{id:1,x:cx-35,y:cy},{id:2,x:cx+35,y:cy}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{id:1,x:cx-50,y:cy+12},{id:2,x:cx+65,y:cy+12}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await settle();
  after=(await state()).scene.camera;
  check(after.zoom>before.zoom && Math.abs(after.panY-before.panY)>5,'Chromium emulated two-finger gesture zooms and pans');
  check((await state()).scene.gesture.pointers===0 && !(await state()).scene.selected,'pinch releases all pointers without accidental selection');
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{id:1,x:cx,y:cy}]});await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
  check((await state()).scene.gesture.pointers===0,'touch cancel releases controls');
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:false});await cdp.detach();
  await page.locator('#reset-view').click();await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'evidence/upgrade-mobile.png',fullPage:true});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'390px mobile layout has no horizontal overflow');
  await page.emulateMedia({reducedMotion:'reduce'});await page.locator('[data-view=top]').click();await frame();
  check((await state()).scene.reducedMotion && !(await state()).scene.animating,'reduced-motion settles without animation');
  check(report.errors.length===0,'no browser runtime errors');
  page.off('pageerror',errorListener);return report;
}
