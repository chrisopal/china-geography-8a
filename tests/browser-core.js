async (page) => {
  const report = {checks: [], pageErrors: []};
  page.on('pageerror', e => report.pageErrors.push(e.message));
  const check = (condition, name) => { if (!condition) throw new Error(name); report.checks.push(name); };
  await page.setViewportSize({width:1500,height:980});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('http://127.0.0.1:8767/');
  await page.waitForFunction(() => window.geographyApp);
  const baseline = await page.evaluate(() => localStorage.getItem('china-geography-8a-v1'));
  await page.evaluate(() => window.geographyApp.selectNode('location'));
  await page.locator('#interaction-options button').nth(0).click();
  check((await page.locator('#interaction-feedback').innerText()).includes('再想一步'), 'wrong interaction explains misconception');
  await page.locator('#interaction-options button').nth(1).click();
  await page.locator('#go-quiz').click();
  await page.locator('#quiz-options button').nth(1).click();
  check(await page.locator('#retry-quiz').isVisible(), 'wrong quiz allows retry');
  await page.locator('#retry-quiz').click();
  await page.locator('#quiz-options button').nth(0).click();
  check(await page.evaluate(() => geographyApp.getState().mastered.includes('location')), 'both exercises required for mastery');
  await page.reload(); await page.waitForFunction(() => window.geographyApp);
  check(await page.evaluate(() => geographyApp.getState().mastered.includes('location')), 'mastery survives reload');
  await page.locator('#search').fill('季风');
  check((await page.locator('.node-button').count()) > 0 && (await page.locator('.node-button').count()) < 15, 'search narrows curriculum');
  await page.locator('.node-button').first().click();
  await page.locator('#search').fill('');
  await page.evaluate(() => geographyApp.selectNode('longitude'));
  await page.locator('.mini-lab summary').click();
  await page.locator('.mini-lab input').fill('135');
  check((await page.locator('.lab-result').innerText()).includes('13:00'), 'longitude calculation changes live');
  await page.evaluate(() => geographyApp.selectNode('population-density'));
  await page.locator('.mini-lab summary').click();
  await page.getByRole('button',{name:'青海（2020）',exact:true}).click();
  check((await page.locator('.lab-result').innerText()).includes('8.2'), '2020 density calculation matches data');
  await page.evaluate(() => geographyApp.selectNode('river-lab'));
  await page.locator('.mini-lab summary').click();
  await page.getByRole('slider',{name:'平均流速（米/秒）',exact:true}).fill('2');
  check((await page.locator('.lab-result').innerText()).includes('40.0'), 'flow = width × depth × mean speed');
  await page.locator('#province-challenge').click();
  const target = await page.evaluate(() => ({index:CHINA_PROVINCES.findIndex(p=>p.id===geographyApp.getState().challenge),id:geographyApp.getState().challenge}));
  await page.locator('#scene').focus();
  // Renderer initializes keyboard province cursor at -1. ] advances to the first province.
  for(let i=0;i<=target.index;i++) await page.keyboard.press(']');
  await page.keyboard.press('Enter');
  check((await page.locator('#challenge-feedback').innerText()).includes('找到了'), 'province challenge accepts actual canvas keyboard selection');
  await page.locator('#challenge-stop').click();
  await page.evaluate(() => geographyApp.selectNode('location'));
  await page.locator('#notes-open').click();
  await page.locator('#note-input').fill('自动验证：同一个地方可用不同参照物定位。');
  await page.locator('#save-note').click();
  check((await page.locator('#notes-list').innerText()).includes('同一个地方'), 'note persisted and rendered');
  const noteDownload = page.waitForEvent('download'); await page.locator('#export-notes').click();
  check((await noteDownload).suggestedFilename().endsWith('.md'), 'notes export');
  await page.locator('#notes .dialog-close').click();
  await page.locator('#audio-open').click();
  const scriptsDownload = page.waitForEvent('download'); await page.locator('#export-scripts').click();
  check((await scriptsDownload).suggestedFilename().endsWith('.csv'), 'TTS script export');
  const wav=Buffer.alloc(44+16000*2);wav.write('RIFF',0);wav.writeUInt32LE(wav.length-8,4);wav.write('WAVEfmt ',8);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(16000,24);wav.writeUInt32LE(32000,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(32000,40);
  await page.locator('#audio-files').setInputFiles({name:'location-01.wav',mimeType:'audio/wav',buffer:wav});
  await page.waitForFunction(()=>document.getElementById('audio-import-status').textContent.includes('已导入 1 段'));
  await page.locator('#workshop .dialog-close').click();
  await page.locator('#play-narration').click();
  await page.waitForFunction(()=>document.getElementById('narration-audio').duration>0);
  check(await page.evaluate(()=>Math.abs(document.getElementById('narration-audio').duration-1)<.05),'imported WAV loaded with real duration');
  await page.reload(); await page.waitForFunction(()=>window.geographyApp);
  check(await page.evaluate(()=>geographyApp.getState().audioIds.includes('location-01')),'audio survives reload via IndexedDB');
  await page.locator('#coverage-open').click();
  check(await page.locator('.coverage-chapter').count()===5,'all five chapters in coverage view');
  await page.locator('#coverage .dialog-close').click();
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>scrollTo(0,0));
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile has no horizontal overflow');
  await page.locator('#menu-toggle').click();
  check(await page.locator('#sidebar').isVisible(),'mobile curriculum drawer opens');
  await page.locator('#menu-close').click();
  await page.screenshot({path:'evidence/mobile-verified.png',fullPage:true});
  check(report.pageErrors.length===0,'no browser runtime errors');
  // This dedicated QA session must not retain synthetic narration or passed exercises.
  await page.evaluate(async baseline=>{
    if(baseline===null)localStorage.removeItem('china-geography-8a-v1');else localStorage.setItem('china-geography-8a-v1',baseline);
    await new Promise((resolve,reject)=>{const req=indexedDB.open('china-geography-audio-v1',1);req.onsuccess=()=>{const db=req.result,tx=db.transaction('clips','readwrite');tx.objectStore('clips').delete('location-01');tx.oncomplete=()=>{db.close();resolve();};tx.onerror=()=>reject(tx.error);};});
  },baseline);
  await page.reload();
  return report;
}
